<script>
/* ── Elements ─────────────────────────────────────────────────────────────── */
const video       = document.getElementById('video');
const faceGuide   = document.getElementById('faceGuide');
const scanLine    = document.getElementById('scanLine');
const faceTick    = document.getElementById('faceTick');
const statusBox   = document.getElementById('statusBox');
const statusText  = document.getElementById('statusText');
const statusSpinn = document.getElementById('statusSpinner');
const progressWrap= document.getElementById('progressWrap');
const progressBar = document.getElementById('progressBar');
const retryWrap   = document.getElementById('retryCameraWrap');
const retryBtn    = document.getElementById('retryCameraBtn');

/* ── State ────────────────────────────────────────────────────────────────── */
// Time-based hold detection: capture after the face has been continuously
// well-positioned for HOLD_DURATION_MS, regardless of how many detection
// callbacks fire in that window. This replaces a frame-count approach
// (accumulate N `onResults` calls) that assumed a steady ~8 callbacks/sec.
// On many mobile devices (and some desktop browsers under load) MediaPipe's
// `send()` → `onResults()` round trip does not keep up with that rate — a
// single detection pass can take anywhere from ~50ms to 500ms+ depending on
// the device — so the frame count advanced far slower than real time, and a
// single slow/late callback (or one frame the model was mid-processing when
// the head moved a few millimeters) reset the counter to 0 and forced the
// full sequence to start over. On slower phones this could effectively
// never finish, which is exactly the "stuck on Hold still…" symptom.
const HOLD_DURATION_MS = 1700; // ~1.7s of continuous good detection required
const MIN_BRIGHTNESS = 45; // 0-255 luma; below this ask for more light
let holdStartTime    = null; // timestamp (ms) when the current unbroken good-detection streak began; null = not currently holding
let detectionBusy    = false; // true while a faceDetection.send() call is in flight
let submitted        = false;
let faceApiReady     = false;
let cameraHandle     = null;

/* ── Status helper ───────────────────────────────────────────────────────── */
function setStatus(msg, type = 'info', spin = true) {
  statusBox.className = `alert mb-0 d-flex align-items-center gap-2 alert-${type}`;
  statusText.textContent = msg;
  statusSpinn.style.display = spin ? '' : 'none';
}

/* ── Model loading with sessionStorage caching ───────────────────────────── */
const MODEL_URL = 'https://cdn.jsdelivr.net/npm/@vladmandic/face-api/model';

async function loadFaceApiModels() {
  try {
    await Promise.all([
      faceapi.nets.tinyFaceDetector.loadFromUri(MODEL_URL),
      faceapi.nets.faceLandmark68TinyNet.loadFromUri(MODEL_URL),
      faceapi.nets.faceRecognitionNet.loadFromUri(MODEL_URL),
    ]);
    faceApiReady = true;
    console.log('face-api.js models loaded');
  } catch (e) {
    console.warn('face-api.js models could not load:', e);
  }
}

/* ── Generate 128-D descriptor ───────────────────────────────────────────── */
async function generateDescriptor() {
  if (!faceApiReady) return null;
  try {
    const det = await faceapi
      .detectSingleFace(video, new faceapi.TinyFaceDetectorOptions({ scoreThreshold: 0.45 }))
      .withFaceLandmarks(true)   // tiny landmarks model
      .withFaceDescriptor();
    return det ? det.descriptor : null;
  } catch (e) {
    console.warn('descriptor error:', e);
    return null;
  }
}

/* ── Capture + submit ────────────────────────────────────────────────────── */
async function captureAndSubmit() {
  if (submitted) return;
  submitted = true;

  // Hide scan line; show tick
  scanLine.style.display = 'none';
  faceTick.classList.remove('d-none');
  faceGuide.classList.add('stable');
  progressWrap.classList.add('d-none');

  setStatus('🔵 Verifying Face... Please stay still.', 'primary', true);

  // Capture JPEG
  const cvs = document.createElement('canvas');
  cvs.width  = video.videoWidth  || 640;
  cvs.height = video.videoHeight || 480;
  cvs.getContext('2d').drawImage(video, 0, 0, cvs.width, cvs.height);
  document.getElementById('face_image').value = cvs.toDataURL('image/jpeg', 0.88);

  // Generate descriptor (fast — already warmed up). Retry automatically a
  // couple of times before giving up — slower mobile devices sometimes miss
  // the first pass while the model is still warming up on this exact frame.
  let desc = await generateDescriptor();
  if (!desc) { await new Promise(r => setTimeout(r, 250)); desc = await generateDescriptor(); }
  if (!desc) { await new Promise(r => setTimeout(r, 400)); desc = await generateDescriptor(); }
  if (desc && desc.length === 128) {
    document.getElementById('face_descriptor').value = JSON.stringify(Array.from(desc));
    setStatus('🔵 Face captured! Submitting verification…', 'success', true);
  } else {
    submitted = false;
    holdStartTime = null;
    faceTick.classList.add('d-none');
    scanLine.style.display = '';
    faceGuide.classList.remove('stable');
    setStatus('🔴 Face recognition data could not be generated. Please check your connection, improve lighting, and try again.', 'danger', false);
    return;
  }

  document.getElementById('faceForm').submit();
}

/* ── Bounding-box helper ─────────────────────────────────────────────────── */
function getBox(det) {
  const b = det.boundingBox || det.locationData?.relativeBoundingBox;
  if (!b) return null;
  return {
    xCenter: b.xCenter ?? (b.xMin  + b.width  / 2),
    yCenter: b.yCenter ?? (b.yMin  + b.height / 2),
    width:   b.width,
    height:  b.height,
  };
}

/* ── Hold-timer reset helper ──────────────────────────────────────────────
 * Per the fix requirements, the hold timer should ONLY be cleared when the
 * face truly disappears, multiple faces appear, the face leaves the guide,
 * or the face becomes too small/too large — never for small natural head
 * movements while still inside the guide, and never merely for a brief dip
 * in lighting (that just pauses the on-screen progress, see below).
 */
function resetHold() {
  holdStartTime = null;
  progressWrap.classList.add('d-none');
  progressBar.style.width = '0%';
  faceGuide.classList.remove('stable');
}

/* ── MediaPipe setup ─────────────────────────────────────────────────────── */
const faceDetection = new FaceDetection({
  locateFile: f => `https://cdn.jsdelivr.net/npm/@mediapipe/face_detection/${f}`
});
faceDetection.setOptions({ model: 'short', minDetectionConfidence: 0.65 });

faceDetection.onResults(results => {
  if (submitted) return;
  const faces = results.detections || [];

  if (faces.length === 0) {
    resetHold();
    setStatus('🟡 No face detected. Please position your face inside the guide.', 'info');
    return;
  }
  if (faces.length > 1) {
    resetHold();
    setStatus('🔴 Multiple faces detected. Please ensure only one person is visible.', 'danger');
    return;
  }

  const box = getBox(faces[0]);
  const tooSmall = box && box.width > 0 && box.width < 0.16;
  const tooLarge = box && box.width > 0.85;
  const centered = box
    && box.xCenter > 0.32 && box.xCenter < 0.68
    && box.yCenter > 0.25 && box.yCenter < 0.75
    && box.width   > 0.16;

  if (tooSmall) {
    resetHold();
    setStatus('🟡 Move closer to the camera.', 'warning');
    return;
  }
  if (tooLarge) {
    resetHold();
    setStatus('🟡 Move back a little — you are too close to the camera.', 'warning');
    return;
  }
  if (!centered) {
    resetHold();
    setStatus('🟡 Center your face inside the guide.', 'warning');
    return;
  }

  const brightness = FaceCamera.estimateBrightness(video);
  if (brightness < MIN_BRIGHTNESS) {
    // Position/size are still fine — this is intentionally NOT one of the
    // reset conditions. A passing shadow or brief glare shouldn't throw away
    // an otherwise-good hold streak; just pause the visible progress until
    // brightness recovers, then continue counting from where it left off.
    progressWrap.classList.add('d-none');
    faceGuide.classList.remove('stable');
    setStatus('🟡 Lighting is too dark. Please improve the lighting.', 'warning');
    return;
  }

  // Face is present, alone, centered, correctly sized, and well lit.
  const now = performance.now();
  if (holdStartTime === null) holdStartTime = now;
  const elapsed = now - holdStartTime;
  const pct = Math.min(100, Math.round((elapsed / HOLD_DURATION_MS) * 100));
  progressWrap.classList.remove('d-none');
  progressBar.style.width = pct + '%';

  if (elapsed >= HOLD_DURATION_MS) {
    captureAndSubmit();
  } else {
    faceGuide.classList.add('stable');
    setStatus('🟢 Face detected. Hold still…', 'success');
  }
});

/* ── Camera + model bootstrap ─────────────────────────────────────────────
 * Uses the shared FaceCamera.start() helper (assets/face-camera.js) instead
 * of the MediaPipe `Camera` utility: it requests getUserMedia directly with
 * a graded fallback of constraints, waits for real decodable video
 * dimensions before starting detection (fixes the black "Camera Ready"
 * preview seen on some Android/Samsung Internet builds), and reports
 * specific, actionable messages for permission-denied / no-camera / camera-
 * in-use / insecure-context failures instead of a single generic error.
 */
async function startCamera() {
  retryWrap.classList.add('d-none');
  setStatus('Requesting camera access…', 'info', true);
  try {
    cameraHandle = await FaceCamera.start(video, {
      fps: 8,
      // Guard against overlapping detection passes: on slower phones a
      // single faceDetection.send() → onResults() round trip can take
      // longer than the ~125ms frame interval above. Without this guard the
      // rAF-driven onFrame() below keeps firing and queues up more send()
      // calls than the model can actually process, which causes onResults
      // to arrive late, out of order, or in bursts — making frame-counted
      // "stability" wildly inconsistent on exactly this kind of device.
      // Waiting for the previous call to finish keeps at most one detection
      // in flight at any time, regardless of device speed.
      onFrame: () => {
        if (submitted || detectionBusy) return;
        detectionBusy = true;
        Promise.resolve(faceDetection.send({ image: video }))
          .catch(e => console.warn('face detection send error:', e))
          .finally(() => { detectionBusy = false; });
      },
      onRetryNotice: (msg) => setStatus(msg, 'warning', true),
    });
    if (faceApiReady) {
      setStatus('Camera ready. Position your face in the oval guide.', 'info');
    } else {
      setStatus('Camera ready. Loading face recognition model…', 'info', true);
    }
  } catch (e) {
    console.warn('Camera start failed:', e);
    setStatus(e.friendlyMessage || FaceCamera.describeCameraError(e), 'danger', false);
    // iOS Safari caches a permission denial for the page session — a JS
    // retry will just fail again silently. A full reload (after the user
    // fixes the setting) is the only thing that re-prompts there.
    const needsReload = (e && (e.name === 'NotAllowedError' || e.name === 'PermissionDeniedError')) && FaceCamera.isIOS();
    retryBtn.innerHTML = needsReload
      ? '<i class="bi bi-arrow-clockwise me-1"></i>Reload Page'
      : '<i class="bi bi-arrow-clockwise me-1"></i>Retry Camera';
    retryBtn.dataset.reload = needsReload ? '1' : '0';
    retryWrap.classList.remove('d-none');
  }
}

retryBtn?.addEventListener('click', () => {
  if (retryBtn.dataset.reload === '1') { window.location.reload(); return; }
  if (cameraHandle) { cameraHandle.stop(); cameraHandle = null; }
  submitted = false; holdStartTime = null; detectionBusy = false;
  startCamera();
});

setStatus('Loading face detection models…', 'info', true);

loadFaceApiModels()
  .then(() => { if (cameraHandle) setStatus('Camera ready. Position your face in the oval guide.', 'info'); })
  .catch(() => setStatus('Face recognition model did not load. Please refresh the page and try again.', 'danger', false));

startCamera();

window.addEventListener('beforeunload', () => { if (cameraHandle) cameraHandle.stop(); });

