<?php
/**
 * faculty/face_verification.php
 * Verifies a live face against the one-time face template captured during registration.
 * This page never replaces the stored biometric template.
 */
require_once __DIR__ . '/../db.php';
session_start();
requireLogin('faculty');

$pageTitle = 'Face Verification';
$facultyId = (int)$_SESSION['user_id'];
$faculty   = getFacultyOnboarding($conn, $facultyId);
if (!$faculty) redirect('/logout.php');

$mode = $_GET['mode'] ?? $_POST['mode'] ?? 'verify';
$isLoginFace = ($mode === 'login');

if ($isLoginFace && (int)($_SESSION['pending_face_user_id'] ?? 0) !== $facultyId) {
    redirect('/faculty/dashboard.php');
}

if (!$isLoginFace && ($faculty['account_status'] ?? 'Active') !== 'Pending Face Verification') {
    redirect('/faculty/dashboard.php');
}

$errors = [];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $dataUrl = $_POST['face_image'] ?? '';
    $descriptorJson = $_POST['face_descriptor'] ?? '';

    // Validate the live face descriptor generated by the browser.
    $descriptor = null;
    if (!empty($descriptorJson)) {
        $decoded = json_decode($descriptorJson, true);
        if (is_array($decoded) && count($decoded) === 128) {
            $descriptor = array_map('floatval', $decoded);
        }
    }
    if ($descriptor === null) {
        $errors[] = 'Face descriptor could not be generated. Please ensure good lighting and try again.';
    }

    // Verify live face against the permanent template captured during registration.
    if (empty($errors)) {
        $stored = json_decode($faculty['face_descriptor'] ?? '', true);
        if (!is_array($stored) || count($stored) !== 128) {
            $errors[] = 'No registered face template found. Please contact the administrator.';
        } else {
            $distance = faceDescriptorDistance(array_map('floatval', $stored), $descriptor);
            if ($distance > 0.55) {
                $errors[] = 'The detected face does not match the registered faculty account. Please use the registered face associated with this account.';
                logActivity($conn, 'EMAIL_OTP_FAILED', "Face verification failed for {$faculty['name']} ({$faculty['email']}); distance={$distance}");
            }
        }
    }

    // Optional audit snapshot only; never replace users.face_descriptor here.
    if (empty($errors) && preg_match('/^data:image\/jpeg;base64,/', $dataUrl)) {
        $uploadDir = dirname(__DIR__) . DIRECTORY_SEPARATOR . 'uploads' . DIRECTORY_SEPARATOR . 'faces';
        if (!is_dir($uploadDir)) mkdir($uploadDir, 0775, true);
        $imageData = base64_decode(substr($dataUrl, strpos($dataUrl, ',') + 1), true);
        if ($imageData !== false) {
            file_put_contents($uploadDir . DIRECTORY_SEPARATOR . "faculty_{$facultyId}_verify.jpg", $imageData);
        }
    }

    if (empty($errors)) {
        logActivity($conn, 'FACE_VERIFIED', "Face verification completed for {$faculty['name']}");

        if ($isLoginFace) {
            if (tableExists($conn, 'email_otps')) {
                $otp = generateOtp($conn, $facultyId, 'login_otp');
                if (!sendOtpEmail($faculty['email'], $faculty['name'], $otp)) {
                    logActivity($conn, 'EMAIL_SEND_FAILED', "Login OTP email FAILED after face verification for {$faculty['email']}: " . getLastMailError());
                    setFlash('danger', 'Unable to send email. [DEBUG] ' . getLastMailError());
                    redirect('/faculty/face_verification.php?mode=login');
                }
                logActivity($conn, 'EMAIL_OTP_SENT', "Login OTP sent to {$faculty['email']} after face verification");
            }
            unset($_SESSION['pending_face_user_id']);
            $_SESSION['pending_otp_user_id'] = $facultyId;
            redirect('/faculty/email_otp.php?mode=login');
        }

        $verifyFields = [];
        if (columnExists($conn, 'users', 'face_verified')) $verifyFields[] = 'face_verified = 1';
        if (columnExists($conn, 'users', 'face_verified_at')) $verifyFields[] = 'face_verified_at = NOW()';
        if ($verifyFields) {
            $fvUpd = $conn->prepare("UPDATE users SET " . implode(', ', $verifyFields) . " WHERE id = ?");
            if ($fvUpd) { $fvUpd->bind_param('i', $facultyId); $fvUpd->execute(); $fvUpd->close(); }
        }
        if (columnExists($conn, 'users', 'account_status')) {
            $stUpd = $conn->prepare("UPDATE users SET account_status = 'Pending Email Verification' WHERE id = ?");
            if ($stUpd) { $stUpd->bind_param('i', $facultyId); $stUpd->execute(); $stUpd->close(); }
        }

        if (tableExists($conn, 'email_otps')) {
            $otp = generateOtp($conn, $facultyId, 'email_verification');
            if (!sendOtpEmail($faculty['email'], $faculty['name'], $otp)) {
                logActivity($conn, 'EMAIL_SEND_FAILED', "OTP email FAILED after face verification for {$faculty['email']}: " . getLastMailError());
                if (columnExists($conn, 'users', 'account_status')) {
                    $rollback = $conn->prepare("UPDATE users SET account_status = 'Pending Face Verification' WHERE id = ?");
                    if ($rollback) { $rollback->bind_param('i', $facultyId); $rollback->execute(); $rollback->close(); }
                }
                setFlash('danger', 'Unable to send email. [DEBUG] ' . getLastMailError());
                redirect('/faculty/face_verification.php');
            }
            logActivity($conn, 'EMAIL_OTP_SENT', "OTP sent to {$faculty['email']} after face verification");
        }

        pushNotification($conn, 'Face Verification Completed',
            "{$faculty['name']} completed face verification. Awaiting email OTP.",
            'success', '/admin/faculty/index.php');

        setFlash('info', 'Face verified! A 6-digit code has been sent to your registered email.');
        redirect('/faculty/email_otp.php');
    }
}
